if (Array.isArray(window.VENUES)) {
  for (const [name, photo] of Object.entries(window.BANYA_PHOTOS)) {
    const venue = window.VENUES.find(v => v.name === name);
    if (!venue) continue;
    venue.img = photo.img;
    venue.gallery = [...new Set(photo.images || [photo.img])];
    venue.banyaPhotoUrl = photo.url;
    if (!String(venue.source || '').includes('Баня.ру')) {
      venue.source = venue.source ? `${venue.source} / Баня.ру фото` : 'Баня.ру фото';
    }
  }
  for (const venue of window.VENUES) {
    if (!Array.isArray(venue.gallery) || !venue.gallery.length) venue.gallery = venue.img ? [venue.img] : [];
  }
}

// MVP: карта + каталог. Заявки, бронирование и внешняя кнопка фото сейчас убраны.
(function simplifyClientMvp(){
  const style = document.createElement('style');
  style.textContent = `
    [data-s="requests"], #requests, #bookModal, #book, .photos { display:none !important; }
    .nav { grid-template-columns:repeat(2,1fr) !important; }
    #call { grid-column:span 2; }
    .hero:after { pointer-events:none; }
    .gallery-track { position:absolute; inset:0; display:flex; overflow-x:auto; overflow-y:hidden; scroll-snap-type:x mandatory; scroll-behavior:smooth; scrollbar-width:none; overscroll-behavior-x:contain; -webkit-overflow-scrolling:touch; }
    .gallery-track::-webkit-scrollbar { display:none; }
    .gallery-track img { flex:0 0 100%; width:100%; height:100%; object-fit:cover; scroll-snap-align:start; scroll-snap-stop:always; }
    .gallery-dots { position:absolute; z-index:4; left:50%; bottom:13px; transform:translateX(-50%); display:flex; gap:5px; padding:5px 7px; border-radius:999px; background:#09100d99; }
    .gallery-dot { width:6px; height:6px; border-radius:50%; background:#ffffff66; transition:.15s; }
    .gallery-dot.on { background:white; transform:scale(1.25); }
    .gallery-count { position:absolute; z-index:4; right:13px; bottom:12px; padding:5px 8px; border-radius:999px; background:#09100dbd; color:white; font-size:11px; }
    .gallery-arrow { position:absolute; z-index:4; top:50%; transform:translateY(-50%); width:36px; height:44px; border:0; border-radius:12px; background:#09100daa; color:white; font-size:22px; }
    .gallery-arrow.prev { left:10px; }
    .gallery-arrow.next { right:10px; }
    @media(max-width:759px){ .gallery-arrow { display:none; } }
  `;
  document.head.appendChild(style);

  function removePausedActions(root=document){
    root.querySelectorAll('#book, .photos').forEach(el => el.remove());
    root.querySelectorAll('button').forEach(btn => {
      const text = (btn.textContent || '').trim().toLowerCase();
      if (text.includes('запросить бронь') || text.includes('смотреть официальные фото')) btn.remove();
    });
  }

  function enhanceGallery(){
    const sheet = document.getElementById('sheet');
    if (!sheet) return;
    removePausedActions(sheet);
    const hero = sheet.querySelector('.hero');
    const title = sheet.querySelector('.detail h2');
    if (!hero || !title || hero.dataset.galleryReady === '1') return;
    const venue = (window.VENUES || []).find(v => v.name === title.textContent.trim());
    if (!venue) return;
    const images = [...new Set((venue.gallery && venue.gallery.length ? venue.gallery : [venue.img]).filter(Boolean))];
    hero.dataset.galleryReady = '1';
    if (images.length < 2) return;

    const oldImg = hero.querySelector(':scope > img');
    if (!oldImg) return;
    const track = document.createElement('div');
    track.className = 'gallery-track';
    track.innerHTML = images.map((src,i) => `<img src="${src}" alt="${venue.name}: фото ${i+1}" loading="${i ? 'lazy' : 'eager'}">`).join('');
    oldImg.replaceWith(track);

    const dots = document.createElement('div');
    dots.className = 'gallery-dots';
    dots.innerHTML = images.map((_,i) => `<span class="gallery-dot${i===0?' on':''}"></span>`).join('');
    hero.appendChild(dots);

    const count = document.createElement('div');
    count.className = 'gallery-count';
    count.textContent = `1 / ${images.length}`;
    hero.appendChild(count);

    const prev = document.createElement('button');
    prev.type = 'button'; prev.className = 'gallery-arrow prev'; prev.textContent = '‹'; prev.setAttribute('aria-label','Предыдущее фото');
    const next = document.createElement('button');
    next.type = 'button'; next.className = 'gallery-arrow next'; next.textContent = '›'; next.setAttribute('aria-label','Следующее фото');
    hero.append(prev,next);

    let current = 0;
    const update = () => {
      current = Math.max(0, Math.min(images.length - 1, Math.round(track.scrollLeft / Math.max(1, track.clientWidth))));
      dots.querySelectorAll('.gallery-dot').forEach((d,i) => d.classList.toggle('on', i === current));
      count.textContent = `${current + 1} / ${images.length}`;
    };
    track.addEventListener('scroll', () => requestAnimationFrame(update), {passive:true});
    prev.addEventListener('click', e => { e.stopPropagation(); track.scrollTo({left:Math.max(0,current-1)*track.clientWidth,behavior:'smooth'}); });
    next.addEventListener('click', e => { e.stopPropagation(); track.scrollTo({left:Math.min(images.length-1,current+1)*track.clientWidth,behavior:'smooth'}); });
  }

  function start(){
    const sheet = document.getElementById('sheet');
    removePausedActions();
    enhanceGallery();
    new MutationObserver(() => {
      removePausedActions(sheet || document);
      enhanceGallery();
    }).observe(sheet || document.body, {childList:true, subtree:true});
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start, {once:true});
  else start();
})();

